<script>
    if (typeof window.ClientPaginator === 'undefined') {
        window.ClientPaginator = class ClientPaginator {
            constructor(config) {
                this.containerId = config.containerId;
                this.container = document.getElementById(config.containerId);
                if (!this.container) return;

                this.pageSize = parseInt(config.pageSize || 10, 10);
                this.currentPage = 1;
                this.getItems = config.getItems;
                this.onPageChange = config.onPageChange;

                this.fromEl = this.container.querySelector('.pagination-from');
                this.toEl = this.container.querySelector('.pagination-to');
                this.totalEl = this.container.querySelector('.pagination-total');
                this.pagesEl = this.container.querySelector('.pagination-pages');
                this.prevBtn = this.container.querySelector('.pagination-prev');
                this.nextBtn = this.container.querySelector('.pagination-next');
                this.sizeSelect = this.container.querySelector('.pagination-size-select');

                this.bindEvents();
                this.update();
            }

            bindEvents() {
                if (this.prevBtn) {
                    this.prevBtn.addEventListener('click', () => {
                        if (this.currentPage > 1) {
                            this.goToPage(this.currentPage - 1);
                        }
                    });
                }
                if (this.nextBtn) {
                    this.nextBtn.addEventListener('click', () => {
                        const items = this.getItems ? this.getItems() : [];
                        const totalPages = Math.max(1, Math.ceil(items.length / this.pageSize));
                        if (this.currentPage < totalPages) {
                            this.goToPage(this.currentPage + 1);
                        }
                    });
                }
                if (this.sizeSelect) {
                    this.sizeSelect.addEventListener('change', (e) => {
                        this.pageSize = parseInt(e.target.value, 10);
                        this.currentPage = 1;
                        this.update();
                    });
                }
                window.addEventListener('resize', () => {
                    if (this.totalEl && this.getItems) {
                        const total = this.getItems().length;
                        const totalPages = Math.max(1, Math.ceil(total / this.pageSize));
                        this.renderPageButtons(totalPages);
                    }
                });
            }

            goToPage(page) {
                this.currentPage = page;
                this.update();
            }

            reset() {
                this.currentPage = 1;
                this.update();
            }

            update() {
                if (!this.getItems) return;
                const allEligibleItems = this.getItems();
                const total = allEligibleItems.length;
                const totalPages = Math.max(1, Math.ceil(total / this.pageSize));

                if (this.currentPage > totalPages) {
                    this.currentPage = totalPages;
                }
                if (this.currentPage < 1) {
                    this.currentPage = 1;
                }

                const startIndex = total === 0 ? 0 : (this.currentPage - 1) * this.pageSize;
                const endIndex = total === 0 ? 0 : Math.min(startIndex + this.pageSize, total);
                const visibleSlice = allEligibleItems.slice(startIndex, endIndex);

                if (this.fromEl) this.fromEl.textContent = total === 0 ? 0 : (startIndex + 1);
                if (this.toEl) this.toEl.textContent = endIndex;
                if (this.totalEl) this.totalEl.textContent = total;

                if (this.prevBtn) {
                    this.prevBtn.disabled = (this.currentPage <= 1);
                }
                if (this.nextBtn) {
                    this.nextBtn.disabled = (this.currentPage >= totalPages);
                }

                this.renderPageButtons(totalPages);

                if (this.onPageChange) {
                    this.onPageChange(visibleSlice, this.currentPage, totalPages, total);
                }
            }

            renderPageButtons(totalPages) {
                if (!this.pagesEl) return;
                this.pagesEl.innerHTML = '';

                if (totalPages <= 1) {
                    const btn = document.createElement('button');
                    btn.type = 'button';
                    btn.className = 'inline-flex h-8 w-8 items-center justify-center rounded-xl bg-blue-600 text-xs font-bold text-white shadow-xs';
                    btn.textContent = '1';
                    this.pagesEl.appendChild(btn);
                    return;
                }

                const isMobile = window.innerWidth < 640;
                const pages = [];
                if (isMobile) {
                    // Mobile: compact pagination (max 4-5 items) so it fits with prev/next buttons
                    if (totalPages <= 4) {
                        for (let i = 1; i <= totalPages; i++) pages.push(i);
                    } else {
                        pages.push(1);
                        if (this.currentPage > 2) pages.push('...');
                        if (this.currentPage > 1 && this.currentPage < totalPages) {
                            pages.push(this.currentPage);
                        }
                        if (this.currentPage < totalPages - 1) pages.push('...');
                        pages.push(totalPages);
                    }
                } else {
                    // Desktop: standard 7-item pagination
                    if (totalPages <= 7) {
                        for (let i = 1; i <= totalPages; i++) pages.push(i);
                    } else {
                        pages.push(1);
                        if (this.currentPage > 3) pages.push('...');
                        const start = Math.max(2, this.currentPage - 1);
                        const end = Math.min(totalPages - 1, this.currentPage + 1);
                        for (let i = start; i <= end; i++) pages.push(i);
                        if (this.currentPage < totalPages - 2) pages.push('...');
                        pages.push(totalPages);
                    }
                }

                pages.forEach(p => {
                    if (p === '...') {
                        const span = document.createElement('span');
                        span.className = 'px-1 text-slate-400 font-mono text-xs';
                        span.textContent = '...';
                        this.pagesEl.appendChild(span);
                    } else {
                        const btn = document.createElement('button');
                        btn.type = 'button';
                        btn.className = (p === this.currentPage)
                            ? 'inline-flex h-8 w-8 items-center justify-center rounded-xl bg-blue-600 text-xs font-bold text-white shadow-xs cursor-default'
                            : 'inline-flex h-8 w-8 items-center justify-center rounded-xl border border-slate-200 bg-white text-xs font-semibold text-slate-700 hover:bg-slate-50 transition cursor-pointer shadow-2xs';
                        btn.textContent = p;
                        btn.addEventListener('click', () => {
                            if (p !== this.currentPage) {
                                this.goToPage(p);
                            }
                        });
                        this.pagesEl.appendChild(btn);
                    }
                });
            }
        };
    }
</script>
